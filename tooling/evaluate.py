#!/usr/bin/env python3
"""Multi-system coverage and ontology-quality evaluation for HCMO.

Reads ``evaluation/multi-system.yaml`` and produces deterministic Markdown
reports under ``evaluation/reports/``:

  coverage.md               native-concept -> HCMO coverage per system and module
  competency-questions.md   cross-system competency questions with exact answers
  shacl.md                  SHACL shape inventory, conformance, probes, negatives
  ontology-metrics.md       per-module term/axiom counts and reused external terms
  reasoner.md               HermiT result (only with --reason; needs Java)

The same checks that back the reports are exposed through ``check_all`` for the
CI gate in ``tooling/validate.py`` (SHACL conformance of every system graph,
negative probes, exact competency answers).

Usage:
  python tooling/evaluate.py                # write reports
  python tooling/evaluate.py --reason       # also run HermiT and write reasoner.md
  python tooling/evaluate.py --print-answers  # print current CQ rows as YAML
"""
